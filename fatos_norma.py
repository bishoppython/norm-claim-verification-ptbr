def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def main() -> int:
    artigos: dict[tuple[str, str], list[str]] = {}
    for linha in (AQUI / "fontes" / "artigos.jsonl").open(encoding="utf-8"):
        a = json.loads(linha)
        artigos.setdefault((a["norma"], a["artigo"]), []).append(norm(a["texto"]))

    ok, falhas = [], []
    for f in FATOS:
        textos = artigos.get((f["norma"], f["artigo"]))
        if not textos:
            falhas.append((f["id"], "artigo não encontrado"))
        elif not any(norm(f["trecho"]) in t for t in textos):
            falhas.append((f["id"], "trecho não é literal da fonte"))
        else:
            ok.append(f)

    with (AQUI / "fatos_norma.jsonl").open("w", encoding="utf-8") as out:
        for f in ok:
            out.write(json.dumps(f, ensure_ascii=False) + "\n")

    print(f"{len(ok)}/{len(FATOS)} fatos validados -> fatos_norma.jsonl")
    for fid, motivo in falhas:
        print(f"  FALHA {fid}: {motivo}")
    return 1 if falhas else 0


if __name__ == "__main__":
    sys.exit(main())
